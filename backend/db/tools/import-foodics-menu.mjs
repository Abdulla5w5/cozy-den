/**
 * Regenerate the menu migration from the live Foodics menu.
 *
 *   node backend/db/tools/import-foodics-menu.mjs > backend/db/migrations/021_menu_from_foodics.sql
 *
 * The Foodics storefront is a Nuxt app that ships its whole catalogue in the
 * served HTML as a `window.__NUXT__` payload, so the menu can be read with one
 * plain GET — no browser, no API key, no scraping of rendered markup.
 *
 * Rerun this whenever the Foodics menu changes and commit the new migration;
 * that keeps the café's own site a plain read from its own database, with no
 * third-party call on the request path.
 *
 * The payload is a minified IIFE rather than JSON, so it has to be evaluated.
 * It is evaluated inside a `node:vm` context with NO globals at all — no
 * require, no process, no fs, no network, and a hard timeout — so the only
 * thing it can do is return data.
 */
import { createContext, runInContext } from 'node:vm';

const MENU_URL = 'https://cozyden.foodics.online/menu/-162282';

// Everything else is food. Matched on the English category name so the mapping
// survives the categories being reordered in Foodics.
const DRINK_WORDS = [
  'coffee', 'tea', 'matcha', 'mocktail', 'juice', 'milkshake', 'shake',
  'soft drink', 'soda', 'drink', 'beverage', 'water',
];

const sqlStr = (v) => `'${String(v ?? '').replace(/'/g, "''")}'`;
const pick = (field, locale) =>
  (field && typeof field === 'object' ? field[locale] : field) || '';

async function loadCategories() {
  const res = await fetch(MENU_URL, { headers: { 'User-Agent': 'cozy-den-menu-import' } });
  if (!res.ok) throw new Error(`Foodics returned ${res.status}`);
  const html = await res.text();

  const start = html.indexOf('window.__NUXT__=');
  if (start === -1) throw new Error('No __NUXT__ payload in the page.');
  // The payload ends at the close of the <script> block that carries it.
  const end = html.indexOf('</script>', start);
  const expr = html.slice(start + 'window.__NUXT__='.length, end).replace(/;\s*$/, '');

  const sandbox = createContext(Object.create(null));
  const payload = runInContext(`(${expr})`, sandbox, { timeout: 5000 });

  const cats = payload?.state?.concept?.categoryItems;
  if (!Array.isArray(cats)) throw new Error('Payload has no state.concept.categoryItems.');
  return cats;
}

const cats = await loadCategories();
const rows = [];
const seen = new Set();
let order = 0;

for (const entry of cats) {
  const cat = entry?.attributes?.category ?? {};
  const sectionEn = pick(cat.name, 'en-us').trim();
  const sectionAr = pick(cat.name, 'ar-sa').trim();
  const haystack = sectionEn.toLowerCase();
  const category = DRINK_WORDS.some((w) => haystack.includes(w)) ? 'drink' : 'food';

  for (const item of entry?.attributes?.items ?? []) {
    const name = pick(item.name, 'en-us').trim();
    if (!name) continue;
    // `name` is uniquely indexed, so a repeat across categories would upsert
    // over the first. Keep the first and report the rest.
    if (seen.has(name.toLowerCase())) {
      process.stderr.write(`duplicate name skipped: ${name} (${sectionEn})\n`);
      continue;
    }
    seen.add(name.toLowerCase());
    order += 1;
    rows.push({
      name,
      nameAr: pick(item.name, 'ar-sa').trim(),
      description: pick(item.description, 'en-us').trim(),
      descriptionAr: pick(item.description, 'ar-sa').trim(),
      // Foodics prices are KD; this app stores hundredths throughout.
      priceCents: Math.round(Number(item.price ?? 0) * 100),
      category,
      sectionEn,
      sectionAr,
      order,
    });
  }
}

const sections = [...new Set(rows.map((r) => `${r.category}: ${r.sectionEn}`))];
process.stderr.write(`${rows.length} items across ${sections.length} sections\n`);
for (const s of sections) process.stderr.write(`  ${s}\n`);

const values = rows
  .map(
    (r) =>
      `  (${sqlStr(r.name)}, ${sqlStr(r.nameAr)}, ${sqlStr(r.category)}, ${r.priceCents}, ` +
      `${sqlStr(r.description)}, ${sqlStr(r.descriptionAr)}, ${sqlStr(r.sectionEn)}, ` +
      `${sqlStr(r.sectionAr)}, ${r.order})`,
  )
  .join(',\n');

process.stdout.write(`-- Menu content matched to the live Foodics menu.
--
-- GENERATED by backend/db/tools/import-foodics-menu.mjs — do not hand-edit.
-- Rerun that script and commit the result when the Foodics menu changes.
--
-- Items are never deleted: booking_items references menu_items, so removing a
-- row would break the line items on past orders. Everything is withdrawn
-- (available = false) and then re-published by name, which both preserves that
-- history and lets staff bring an old item back from the editor.
BEGIN;

ALTER TABLE menu_items
  ADD COLUMN IF NOT EXISTS name_ar        TEXT    NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS description_ar TEXT    NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS section        TEXT    NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS section_ar     TEXT    NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS display_order  INTEGER NOT NULL DEFAULT 0;

-- Anything not on the new menu simply stops being offered.
UPDATE menu_items SET available = FALSE;

INSERT INTO menu_items
  (name, name_ar, category, price_cents, description, description_ar,
   section, section_ar, display_order, available)
SELECT v.name, v.name_ar, v.category, v.price_cents, v.description, v.description_ar,
       v.section, v.section_ar, v.display_order, TRUE
  FROM (VALUES
${values}
  ) AS v(name, name_ar, category, price_cents, description, description_ar,
         section, section_ar, display_order)
ON CONFLICT (name) DO UPDATE SET
  name_ar        = EXCLUDED.name_ar,
  category       = EXCLUDED.category,
  price_cents    = EXCLUDED.price_cents,
  description    = EXCLUDED.description,
  description_ar = EXCLUDED.description_ar,
  section        = EXCLUDED.section,
  section_ar     = EXCLUDED.section_ar,
  display_order  = EXCLUDED.display_order,
  available      = TRUE;

-- The menu page reads only what is on offer, in menu order.
CREATE INDEX IF NOT EXISTS menu_items_available_order
  ON menu_items (display_order) WHERE available;

COMMIT;
`);
